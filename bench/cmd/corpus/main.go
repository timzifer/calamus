// Command corpus prepares and lists the benchmark corpus.
//
//	go run ./cmd/corpus fetch   # download the PDFs into testdata/pdf
//	go run ./cmd/corpus list    # every fixture: size, type, source, licence, status
//	go run ./cmd/corpus pixels  # rewrite corpus/pixels.go from the current renders
//
// The libjxl test data is a git submodule:
//
//	git submodule update --init bench/testdata/libjxl
//
// pixels is for a deliberate change of cera, figure or a generator: the
// checksums record what is measured, so a change of them changes the
// corpus and belongs in its own commit.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/tabwriter"
	"time"

	"github.com/timzifer/calamus/bench/corpus"
)

const dir = "testdata"

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: corpus fetch|list|pixels")
		os.Exit(2)
	}
	var err error
	switch os.Args[1] {
	case "fetch":
		err = fetch()
	case "list":
		err = list()
	case "pixels":
		err = pixels()
	default:
		err = fmt.Errorf("unknown command %q", os.Args[1])
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "corpus:", err)
		os.Exit(1)
	}
}

func fetch() error {
	client := &http.Client{Timeout: 2 * time.Minute}
	var failed int
	for _, d := range corpus.Downloads() {
		path := filepath.Join(dir, filepath.FromSlash(d.File))
		data, err := os.ReadFile(path)
		if err != nil {
			if data, err = download(client, d.URL); err != nil {
				fmt.Printf("FAIL %s: %v\n", d.File, err)
				failed++
				continue
			}
		}
		s := sha256.Sum256(data)
		if got := hex.EncodeToString(s[:]); got != d.SHA256 {
			fmt.Printf("FAIL %s: SHA-256 %s, want %s\n", d.File, got, d.SHA256)
			failed++
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return err
		}
		fmt.Printf("ok   %s\n", d.File)
	}
	if failed > 0 {
		return fmt.Errorf("%d files failed", failed)
	}
	return nil
}

func download(c *http.Client, url string) ([]byte, error) {
	resp, err := c.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(io.LimitReader(resp.Body, 64<<20))
}

func list() error {
	w := tabwriter.NewWriter(os.Stdout, 0, 0, 2, ' ', 0)
	fmt.Fprintln(w, "fixture\tsuite\tkind\tpixels\ttype\tstatus\tsource\tlicence")
	var bad int
	for _, f := range corpus.All() {
		suite, kind := "full", "synthetic"
		if f.Short {
			suite = "short"
		}
		if f.Real {
			kind = "real"
		}
		dims, typ, status := "-", "-", "ok"
		m, err := f.Load(dir)
		switch {
		case errors.Is(err, corpus.ErrMissing):
			status = "missing"
		case err != nil:
			status = "FAIL: " + err.Error()
			bad++
		default:
			dims = fmt.Sprintf("%dx%d", m.Bounds().Dx(), m.Bounds().Dy())
			typ = strings.TrimPrefix(fmt.Sprintf("%T", m), "*image.")
		}
		fmt.Fprintf(w, "%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n", f.Name, suite, kind, dims, typ, status, f.Source, f.License)
	}
	w.Flush()
	if bad > 0 {
		return fmt.Errorf("%d fixtures failed", bad)
	}
	return nil
}

func pixels() error {
	sums := map[string]string{}
	for _, f := range corpus.All() {
		m, err := f.LoadUnchecked(dir)
		if err != nil {
			return err
		}
		sums[f.Name] = corpus.PixelSHA256(m)
		fmt.Println(sums[f.Name][:12], f.Name)
	}
	names := make([]string, 0, len(sums))
	for n := range sums {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("// Code generated by \"go run ./cmd/corpus pixels\"; DO NOT EDIT.\n\npackage corpus\n\nvar pixelSHA256 = map[string]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, sums[n])
	}
	b.WriteString("}\n")
	return os.WriteFile(filepath.Join("corpus", "pixels.go"), []byte(b.String()), 0o644)
}
